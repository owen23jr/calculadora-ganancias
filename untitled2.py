print("CALCULADORA DE GANANCIAS")

producto = input("Nombre del producto: ")
precio = float(input("Precio de venta: S/ "))
costo = float(input("Costo de preparacion: S/ "))
cantidad = int(input("Unidades vendidas: "))

ganancia = (precio - costo) * cantidad

print("Producto:", producto)
print("Ganancia total: S/", round(ganancia, 2))