print("=" * 45)
print("     SISTEMA DE GESTIÓN DE GANANCIAS")
print("=" * 45)

nombre = input("Por favor, ingrese su nombre: ").strip()

if nombre == "":
    nombre = "usuario"

print(f"\nBuenos días, {nombre}.")
print("Le damos la bienvenida a nuestro sistema.")

while True:
    print("\n========== MENÚ PRINCIPAL ==========")
    print("1. Calcular ganancias")
    print("2. Salir")

    opcion = input("Seleccione una opción: ").strip()

    if opcion == "1":
        # Validar el costo
        while True:
            try:
                costo = float(input("Costo por producto: S/ "))

                if costo < 0:
                    print("Error: el costo no puede ser negativo.")
                else:
                    break

            except ValueError:
                print("Error: ingrese un número válido.")

        # Validar el precio de venta
        while True:
            try:
                precio = float(input("Precio de venta: S/ "))

                if precio < 0:
                    print("Error: el precio no puede ser negativo.")
                else:
                    break

            except ValueError:
                print("Error: ingrese un número válido.")

        # Validar la cantidad
        while True:
            try:
                cantidad = int(input("Cantidad vendida: "))

                if cantidad < 0:
                    print("Error: la cantidad no puede ser negativa.")
                else:
                    break

            except ValueError:
                print("Error: ingrese una cantidad entera.")

        # Calcular los resultados
        ingresos = precio * cantidad
        costos = costo * cantidad
        ganancia = ingresos - costos

        print("\n========== RESULTADOS ==========")
        print(f"Ingresos totales: S/ {ingresos:.2f}")
        print(f"Costos totales:   S/ {costos:.2f}")
        print(f"Ganancia total:   S/ {ganancia:.2f}")

        if ganancia > 0:
            print("Resultado: El negocio obtuvo ganancias.")
        elif ganancia < 0:
            print("Resultado: El negocio tuvo pérdidas.")
        else:
            print("Resultado: El negocio no ganó ni perdió.")

    elif opcion == "2":
        print(f"\nHasta luego, {nombre}.")
        print("Gracias por utilizar nuestro sistema.")
        print("¡Que tenga un excelente día!")
        break

    else:
        print("Opción incorrecta. Seleccione 1 o 2.")